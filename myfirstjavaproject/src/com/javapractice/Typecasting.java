package com.javapractice;

public class Typecasting {

	public static void main(String[] args) {
		
		int a=10;
		double b=(int)a;
		
		double c=27.7;
		int y=(int)c;
		
		char d='A';
		int e=(int)d;
		
		int f=20;
		char z=(char)f;
		
		System.out.println("Integer to double:"+b);
		System.out.println("Double to integer:"+y);
		System.out.println("Character to integer:"+e);
		System.out.println("Integer to char:"+z);


	}

}
